CREATE TABLE public.exercise_settings (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp with time zone,
    updated_at timestamp with time zone,
    user_id bigint NOT NULL,
    exercise_id bigint NOT NULL,
    machine_settings jsonb,
    CONSTRAINT fk_exercise_settings_user FOREIGN KEY (user_id) REFERENCES public.users (id),
    -- A plain FK is enough: everyone may read the catalog, so there is nothing to leak.
    CONSTRAINT fk_exercise_settings_exercise FOREIGN KEY (exercise_id) REFERENCES public.exercises (id) ON DELETE CASCADE,
    CONSTRAINT uq_exercise_settings_user_exercise UNIQUE (user_id, exercise_id)
);

-- 2. Backfill: parents to the one admin, children from their parent, settings from the old column.
DO $$
DECLARE
  admins bigint;
  owner_id bigint;
BEGIN
  IF EXISTS (SELECT 1 FROM public.exercises)
     OR EXISTS (SELECT 1 FROM public.workout_programs)
     OR EXISTS (SELECT 1 FROM public.workout_plans)
     OR EXISTS (SELECT 1 FROM public.workout_logs) THEN
    SELECT count(*), min(id) INTO admins, owner_id FROM public.users WHERE is_admin AND deleted_at IS NULL;
    IF admins = 0 AND NOT EXISTS (SELECT 1 FROM public.exercises)
       AND NOT EXISTS (SELECT 1 FROM public.workout_plans) AND NOT EXISTS (SELECT 1 FROM public.workout_logs) THEN
      -- A fresh database: only the baseline's placeholder 'Default' program exists and nobody
      -- can own it. A new user starts with no program (the plans page has an empty state for it).
      DELETE FROM public.workout_programs;
    ELSIF admins <> 1 THEN
      RAISE EXCEPTION 'workout: % live admin accounts, expected exactly one to own the existing rows', admins;
    ELSE
    INSERT INTO public.exercise_settings (created_at, updated_at, user_id, exercise_id, machine_settings)
      SELECT now(), now(), owner_id, id, machine_settings
      FROM public.exercises WHERE machine_settings IS NOT NULL;
    UPDATE public.exercises SET created_by = owner_id WHERE created_by IS NULL;
    UPDATE public.workout_programs SET user_id = owner_id WHERE user_id IS NULL;
    UPDATE public.workout_plans SET user_id = owner_id WHERE user_id IS NULL;
    UPDATE public.workout_logs SET user_id = owner_id WHERE user_id IS NULL;
    -- Children take their parent's owner; a row whose parent column is NULL falls back to the admin.
    UPDATE public.workout_plan_days c SET user_id = p.user_id
      FROM public.workout_plans p WHERE p.id = c.workout_plan_id AND c.user_id IS NULL;
    UPDATE public.workout_plan_exercises c SET user_id = p.user_id
      FROM public.workout_plans p WHERE p.id = c.workout_plan_id AND c.user_id IS NULL;
    UPDATE public.logged_exercises c SET user_id = p.user_id
      FROM public.workout_logs p WHERE p.id = c.workout_log_id AND c.user_id IS NULL;
    UPDATE public.logged_exercises SET user_id = owner_id WHERE user_id IS NULL;
    UPDATE public.logged_sets c SET user_id = p.user_id
      FROM public.logged_exercises p WHERE p.id = c.logged_exercise_id AND c.user_id IS NULL;
    UPDATE public.logged_sets SET user_id = owner_id WHERE user_id IS NULL;
    UPDATE public.cardios c SET user_id = p.user_id
      FROM public.workout_logs p WHERE p.id = c.workout_log_id AND c.user_id IS NULL;
    UPDATE public.cardios SET user_id = owner_id WHERE user_id IS NULL;
    END IF;
  END IF;
END $$;
