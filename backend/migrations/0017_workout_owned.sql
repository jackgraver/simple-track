-- Workout module (lane C3, docs/multi-user/DECISIONS.md "C3 workout").
--
-- exercises become a shared catalog (created_by, catalog policies, catalog_guard). What was personal
-- on an exercise (machine_settings, migration 0003) moves to the new per-user table
-- exercise_settings. Programs, plans, logs and everything under them become owned: parents carry
-- user_id, children carry it too with composite FKs (parent_id, user_id) so a row can't be attached
-- to another user's parent (FK checks bypass RLS). All existing rows go to the one admin.

-- migrate:up

-- 0. Legacy duplicates: workout_logs.date had no unique index. Keep the oldest live log per date
-- and soft-delete the extras when they are empty (prod had one empty pair). An extra that holds
-- data is not guessed at: the migration stops so it can be merged by hand.
DO $$
DECLARE
  extra_with_data bigint;
BEGIN
  CREATE TEMP TABLE _dup_logs ON COMMIT DROP AS
    SELECT id FROM (
      SELECT id, row_number() OVER (PARTITION BY date ORDER BY id) AS n
      FROM public.workout_logs WHERE deleted_at IS NULL
    ) ranked WHERE n > 1;
  SELECT count(*) INTO extra_with_data FROM public.workout_logs w
    WHERE w.id IN (SELECT id FROM _dup_logs)
      AND (EXISTS (SELECT 1 FROM public.logged_exercises e WHERE e.workout_log_id = w.id AND e.deleted_at IS NULL)
        OR EXISTS (SELECT 1 FROM public.cardios c WHERE c.workout_log_id = w.id AND c.deleted_at IS NULL)
        OR jsonb_array_length(COALESCE(w.pre_mobility_checked, '[]'::jsonb)) > 0
        OR jsonb_array_length(COALESCE(w.post_mobility_checked, '[]'::jsonb)) > 0);
  IF extra_with_data > 0 THEN
    RAISE EXCEPTION 'workout_logs: % duplicate-date logs hold data; merge them by hand before this migration', extra_with_data;
  END IF;
  UPDATE public.workout_logs SET deleted_at = now() WHERE id IN (SELECT id FROM _dup_logs);
END $$;

