-- Money module (lane C4, docs/multi-user/DECISIONS.md "C4 money").
--
-- investment_account_types and investment_contribution_rules become a shared catalog (created_by,
-- catalog policies, catalog_guard). What was personal on a type (contribution_start_year,
-- opening_room_year, opening_room) moves to the new per-user table investment_contribution_room.
-- investment_accounts becomes owned; account_balances and investment_deposits are its owned
-- children (composite FK on (account_id, user_id)). All existing rows go to the one admin.

-- migrate:up

-- 1. Per-user room settings, filled from the columns on the type before they are dropped.
CREATE TABLE public.investment_contribution_room (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp with time zone,
    updated_at timestamp with time zone,
    user_id bigint NOT NULL,
    investment_account_type_id bigint NOT NULL,
    contribution_start_year bigint,
    opening_room_year bigint,
    opening_room numeric(14,2),
    CONSTRAINT fk_investment_contribution_room_user FOREIGN KEY (user_id) REFERENCES public.users (id),
    CONSTRAINT fk_investment_contribution_room_type FOREIGN KEY (investment_account_type_id)
      REFERENCES public.investment_account_types (id) ON DELETE CASCADE,
    CONSTRAINT uq_investment_contribution_room_user_type UNIQUE (user_id, investment_account_type_id)
);
CREATE INDEX idx_investment_contribution_room_user_id ON public.investment_contribution_room USING btree (user_id);

-- 2. Catalog: investment_account_types.
ALTER TABLE public.investment_account_types ADD COLUMN created_by bigint;
DO $$
DECLARE
  admins bigint;
  owner_id bigint;
BEGIN
  IF EXISTS (SELECT 1 FROM public.investment_account_types) THEN
    SELECT count(*), min(id) INTO admins, owner_id FROM public.users WHERE is_admin AND deleted_at IS NULL;
    IF admins <> 1 THEN
      RAISE EXCEPTION 'investment_account_types: % live admin accounts, expected exactly one to own the existing rows', admins;
    END IF;
    INSERT INTO public.investment_contribution_room
        (created_at, updated_at, user_id, investment_account_type_id,
         contribution_start_year, opening_room_year, opening_room)
      SELECT now(), now(), owner_id, id, contribution_start_year, opening_room_year, opening_room
      FROM public.investment_account_types
      WHERE deleted_at IS NULL
        AND (contribution_start_year IS NOT NULL OR opening_room_year IS NOT NULL OR opening_room IS NOT NULL);
    UPDATE public.investment_account_types SET created_by = owner_id WHERE created_by IS NULL;
  END IF;
END $$;
ALTER TABLE public.investment_account_types DROP COLUMN contribution_start_year;
ALTER TABLE public.investment_account_types DROP COLUMN opening_room_year;
ALTER TABLE public.investment_account_types DROP COLUMN opening_room;
ALTER TABLE public.investment_account_types ALTER COLUMN created_by SET NOT NULL;
ALTER TABLE public.investment_account_types
  ADD CONSTRAINT fk_investment_account_types_created_by FOREIGN KEY (created_by) REFERENCES public.users (id);
CREATE INDEX idx_investment_account_types_created_by ON public.investment_account_types USING btree (created_by);
ALTER TABLE public.investment_account_types ENABLE ROW LEVEL SECURITY;
CREATE POLICY catalog_read ON public.investment_account_types FOR SELECT
  USING (public.app_user_id() IS NOT NULL);
CREATE POLICY catalog_add ON public.investment_account_types FOR INSERT
  WITH CHECK (created_by = public.app_user_id());
CREATE POLICY catalog_edit ON public.investment_account_types FOR UPDATE
  USING (created_by = public.app_user_id() OR public.app_is_admin())
  WITH CHECK (created_by = public.app_user_id() OR public.app_is_admin());
CREATE POLICY catalog_delete ON public.investment_account_types FOR DELETE
  USING (public.app_is_admin());
CREATE TRIGGER catalog_guard BEFORE UPDATE ON public.investment_account_types
  FOR EACH ROW EXECUTE FUNCTION public.catalog_guard();

-- 3. Catalog: investment_contribution_rules (the per-year limits). A row's creator is its type's
-- creator. Unlike the plain catalog UPDATE policy, the type's creator can also edit a limit row
-- somebody else (the admin) added to their type, so a type's limits always stay editable by
-- whoever owns the type.
ALTER TABLE public.investment_contribution_rules ADD COLUMN created_by bigint;
UPDATE public.investment_contribution_rules r SET created_by = t.created_by
  FROM public.investment_account_types t WHERE t.id = r.investment_account_type_id;
ALTER TABLE public.investment_contribution_rules ALTER COLUMN created_by SET NOT NULL;
ALTER TABLE public.investment_contribution_rules
  ADD CONSTRAINT fk_investment_contribution_rules_created_by FOREIGN KEY (created_by) REFERENCES public.users (id);
CREATE INDEX idx_investment_contribution_rules_created_by ON public.investment_contribution_rules USING btree (created_by);
ALTER TABLE public.investment_contribution_rules ENABLE ROW LEVEL SECURITY;
CREATE POLICY catalog_read ON public.investment_contribution_rules FOR SELECT
  USING (public.app_user_id() IS NOT NULL);
CREATE POLICY catalog_add ON public.investment_contribution_rules FOR INSERT
  WITH CHECK (created_by = public.app_user_id());
CREATE POLICY catalog_edit ON public.investment_contribution_rules FOR UPDATE
  USING (created_by = public.app_user_id() OR public.app_is_admin()
         OR EXISTS (SELECT 1 FROM public.investment_account_types t
                    WHERE t.id = investment_account_type_id AND t.created_by = public.app_user_id()))
  WITH CHECK (created_by = public.app_user_id() OR public.app_is_admin()
         OR EXISTS (SELECT 1 FROM public.investment_account_types t
                    WHERE t.id = investment_account_type_id AND t.created_by = public.app_user_id()));
CREATE POLICY catalog_delete ON public.investment_contribution_rules FOR DELETE
  USING (public.app_is_admin());
CREATE TRIGGER catalog_guard BEFORE UPDATE ON public.investment_contribution_rules
  FOR EACH ROW EXECUTE FUNCTION public.catalog_guard();

-- 4. Per-user room: owned.
ALTER TABLE public.investment_contribution_room ENABLE ROW LEVEL SECURITY;
CREATE POLICY owner ON public.investment_contribution_room
  USING (user_id = public.app_user_id())
  WITH CHECK (user_id = public.app_user_id());

-- 5. Owned: investment_accounts.
ALTER TABLE public.investment_accounts ADD COLUMN user_id bigint;
DO $$
DECLARE
  admins bigint;
  owner_id bigint;
BEGIN
  IF EXISTS (SELECT 1 FROM public.investment_accounts WHERE user_id IS NULL) THEN
    SELECT count(*), min(id) INTO admins, owner_id FROM public.users WHERE is_admin AND deleted_at IS NULL;
    IF admins <> 1 THEN
      RAISE EXCEPTION 'investment_accounts: % live admin accounts, expected exactly one to own the existing rows', admins;
    END IF;
    UPDATE public.investment_accounts SET user_id = owner_id WHERE user_id IS NULL;
  END IF;
END $$;
