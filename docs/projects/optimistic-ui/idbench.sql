-- Throwaway ID-strategy benchmark. Runs in schema idbench, dropped at the end.
DROP SCHEMA IF EXISTS idbench CASCADE;
CREATE SCHEMA idbench;
SET search_path = idbench;

-- UUIDv7 emulation for PG16 (PG18 has uuidv7()): 48-bit unix ms + version/variant bits.
CREATE FUNCTION uuid7() RETURNS uuid LANGUAGE sql VOLATILE AS $$
  SELECT encode(
    set_bit(set_bit(
      overlay(uuid_send(gen_random_uuid())
              PLACING substring(int8send((extract(epoch FROM clock_timestamp())*1000)::bigint) FROM 3)
              FROM 1 FOR 6),
    52, 1), 53, 1), 'hex')::uuid;
$$;

-- Same, but with an explicit ms timestamp (to model real traffic: one insert per ms or slower).
CREATE FUNCTION uuid7_at(ms bigint) RETURNS uuid LANGUAGE sql VOLATILE AS $$
  SELECT encode(overlay(uuid_send(gen_random_uuid()) PLACING substring(int8send(ms) FROM 3) FROM 1 FOR 6), 'hex')::uuid;
$$;

-- Shape of logged_sets (+ FK column index, which baseline lacks but any real schema wants).
CREATE TABLE a_bigint (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz, updated_at timestamptz, deleted_at timestamptz,
  logged_exercise_id bigint, reps bigint, weight numeric, weight_setup text);
CREATE INDEX ON a_bigint (logged_exercise_id);

CREATE TABLE b_bigint_cid (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_id uuid NOT NULL UNIQUE,
  created_at timestamptz, updated_at timestamptz, deleted_at timestamptz,
  logged_exercise_id bigint, reps bigint, weight numeric, weight_setup text);
CREATE INDEX ON b_bigint_cid (logged_exercise_id);

CREATE TABLE c_uuid7 (id uuid PRIMARY KEY,
  created_at timestamptz, updated_at timestamptz, deleted_at timestamptz,
  logged_exercise_id uuid, reps bigint, weight numeric, weight_setup text);
CREATE INDEX ON c_uuid7 (logged_exercise_id);

CREATE TABLE d_uuid4 (id uuid PRIMARY KEY,
  created_at timestamptz, updated_at timestamptz, deleted_at timestamptz,
  logged_exercise_id uuid, reps bigint, weight numeric, weight_setup text);
CREATE INDEX ON d_uuid4 (logged_exercise_id);

CREATE TABLE e_uuid7_spaced (id uuid PRIMARY KEY,
  created_at timestamptz, updated_at timestamptz, deleted_at timestamptz,
  logged_exercise_id uuid, reps bigint, weight numeric, weight_setup text);
CREATE INDEX ON e_uuid7_spaced (logged_exercise_id);

-- Pre-generate parent ids so the FK column has realistic (6 sets per parent) clustering.
CREATE TEMP TABLE parents_u7 AS SELECT g, uuid7() AS u FROM generate_series(0, :n/6) g;
CREATE TEMP TABLE parents_u7s AS SELECT g, uuid7_at(1700000000000 + g*6000) AS u FROM generate_series(0, :n/6) g;
CREATE TEMP TABLE parents_u4 AS SELECT g, gen_random_uuid() AS u FROM generate_series(0, :n/6) g;

\echo '== insert :n rows (a bigint, b bigint+client uuid, c uuid7 bulk, d uuid4, e uuid7 spaced 1s)'
\timing on
