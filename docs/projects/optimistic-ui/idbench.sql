\echo '== sizes'
SELECT c.relname AS rel,
       pg_size_pretty(pg_relation_size(c.oid)) AS heap,
       pg_size_pretty(pg_indexes_size(c.oid)) AS all_indexes,
       pg_size_pretty(pg_total_relation_size(c.oid)) AS total
FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE n.nspname = 'idbench' AND c.relkind = 'r' ORDER BY 1;
SELECT i.relname AS index, pg_size_pretty(pg_relation_size(i.oid)) AS size
FROM pg_class i JOIN pg_namespace n ON n.oid = i.relnamespace
WHERE n.nspname = 'idbench' AND i.relkind = 'i' ORDER BY 1;

