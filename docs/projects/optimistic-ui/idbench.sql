  SELECT uuid7(), now(), now(), p.u, 10, 135, '' FROM generate_series(1, :n) s(i) JOIN parents_u7 p ON p.g = s.i/6;
INSERT INTO d_uuid4 (id, created_at, updated_at, logged_exercise_id, reps, weight, weight_setup)
  SELECT gen_random_uuid(), now(), now(), p.u, 10, 135, '' FROM generate_series(1, :n) s(i) JOIN parents_u4 p ON p.g = s.i/6;

INSERT INTO e_uuid7_spaced (id, created_at, updated_at, logged_exercise_id, reps, weight, weight_setup)
  SELECT uuid7_at(1700000000000 + s.i*1000), now(), now(), p.u, 10, 135, '' FROM generate_series(1, :n) s(i) JOIN parents_u7s p ON p.g = s.i/6;
\timing off
